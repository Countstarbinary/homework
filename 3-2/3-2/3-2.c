int strcmp(char* s1, char* s2) 
{
	
	while(*s1 != 0)
	{
		if (*s1 != *s2)
		{
			return 0;
		};
		s1++;
		s2++;
	};
	if (*s2==0)
	{
		return 1;
	};
	return 0;
};


